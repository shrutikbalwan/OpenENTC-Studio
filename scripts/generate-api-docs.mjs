#!/usr/bin/env node
// Package API reference: for every packages/<name>/src/index.mjs, list its purpose (the header
// comment), its public exports and the declaration files that type them. Writes docs/api/packages.md;
// `--check` fails if the file is out of date (used by tests).
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'docs/api/packages.md');

/** Names exported by a module, following `export * from` and `export { … } from` chains. */
function exportedNames(file, seen = new Set()) {
  if (seen.has(file) || !existsSync(file)) return [];
  seen.add(file);
  const text = readFileSync(file, 'utf8');
  const names = new Set();
  for (const m of text.matchAll(/^export\s+(?:async\s+)?(?:function\s*\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
  for (const m of text.matchAll(/^export\s*\{([^}]*)\}/gm)) for (const part of m[1].split(',')) { const n = part.trim().split(/\s+as\s+/).pop(); if (n) names.add(n); }
  for (const m of text.matchAll(/^export\s*\*\s*from\s+'(\.[^']+)'/gm)) for (const n of exportedNames(path.resolve(path.dirname(file), m[1]), seen)) names.add(n);
  return [...names];
}

export function describePackage(name) {
  const dir = path.join(root, 'packages', name, 'src');
  const entry = path.join(dir, 'index.mjs');
  if (!existsSync(entry)) return null;
  const text = readFileSync(entry, 'utf8');
  const header = [];
  for (const line of text.split('\n')) {
    if (/^\/\/ @ts-check/.test(line)) continue;
    if (/^\/\//.test(line)) header.push(line.replace(/^\/\/\s?/, '')); else if (header.length || line.trim()) break;
  }
  const exports = new Set();
  for (const m of text.matchAll(/^export\s+(?:async\s+)?(?:function\s*\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) exports.add(m[1]);
  for (const m of text.matchAll(/^export\s*\{([^}]*)\}/gm)) for (const part of m[1].split(',')) { const n = part.trim().split(/\s+as\s+/).pop(); if (n) exports.add(n); }
  for (const m of text.matchAll(/^export\s*\*\s*from\s+'(\.[^']+)'/gm)) for (const name of exportedNames(path.join(dir, m[1]))) exports.add(name);
  const declarations = readdirSync(dir).filter((f) => /\.d\.(m?ts)$/.test(f)).sort();
  return { name, summary: header.join(' ').replace(/\s+/g, ' ').trim(), exports: [...exports].sort((a, b) => a.localeCompare(b)), declarations };
}

export function render() {
  const names = readdirSync(path.join(root, 'packages'), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();
  const packages = names.map(describePackage).filter(Boolean);
  const lines = ['# Package API reference (generated)', '', 'Generated by `node scripts/generate-api-docs.mjs` from each package\'s `src/index.mjs` and its', 'declaration files. Do not edit by hand; the test suite fails when this file is out of date.', '', `${packages.length} packages. Each section gives the package's purpose, the declaration files that type its public interface, and its exported names.`, ''];
  for (const p of packages) {
    lines.push(`## ${p.name}`, '', p.summary || '_No header comment._', '', `- Types: ${p.declarations.length ? p.declarations.map((d) => `\`${d}\``).join(', ') : '**none**'}`, `- Exports (${p.exports.length}): ${p.exports.map((e) => (e.startsWith('(') ? e : `\`${e}\``)).join(', ') || '—'}`, '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = existsSync(output) ? readFileSync(output, 'utf8') : '';
    if (current !== text) { console.error('docs/api/packages.md is out of date: run node scripts/generate-api-docs.mjs'); process.exit(1); }
    console.log('Package API reference is up to date.');
  } else {
    mkdirSync(path.dirname(output), { recursive: true });
    writeFileSync(output, text);
    console.log(`Wrote ${path.relative(root, output)}.`);
  }
}
